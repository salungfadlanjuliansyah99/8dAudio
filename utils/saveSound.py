from settings import *
import soundfile as sf
from os import remove as removeFile
from pydub import AudioSegment


def saveSound(sound, sampleRate):
    """
    Save the sound in MP3 format.
    Supports both numpy arrays and pydub AudioSegment objects.
    """
    wav_path = outputFile + ".wav"

    if hasattr(sound, "export"):
        sound.export(wav_path, format="wav")
    else:
        if hasattr(sound, "shape"):
            arr = sound
            if len(arr.shape) == 1:
                channels = 1
            else:
                channels = arr.shape[1]
            with sf.SoundFile(
                wav_path,
                "w",
                samplerate=sampleRate,
                channels=channels,
            ) as f:
                f.write(arr)
        else:
            raise TypeError("Unsupported sound type for saveSound().")

    AudioSegment.from_wav(wav_path).export(outputFile + ".mp3", format="mp3")
    removeFile(wav_path)







































































































































































































































































